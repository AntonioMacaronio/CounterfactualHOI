"""Build the static project website (GitHub Pages-ready) from the generated outputs.

  python scripts/site/build_site.py [--out ../CounterfactualHOI-site]      (any python3 >= 3.8, stdlib only)

OUT is the clone of the site repo (github.com/AntonioMacaronio/CounterfactualHOI-site, served by GitHub Pages
from main / root); commit and push there after a rebuild.

The home page follows the reconstruction work in order, one section per method, each with an embedded viewer and
a link to all of that method's viewers:
  1. Do-as-I-Do on the 4 IMG_5710 videos (the real clip + 3 MiniMax H3 edits)      -> recon/daid/
  2. Open-CHOIR on the 10 real videos                                               -> recon/choir/
  3. our pipeline (Depth Pro 2 + hand scale, SAM3, textured SAM3D, FoundationPose)   -> recon/ours/
then the generated-video gallery (videos/) and the retargeting test (img/). Sources: ../outputs/{recon_viser,
choir_viser,fprecon_viser,minimax_h3} (scripts/daid/build_recon_html.py, scripts/choir/build_choir_html.py
[--method fprecon]) and ../videos/grid2x2.mp4. The viser viewers are self-contained HTML files, so the site is
plain static files (plus .nojekyll so GitHub Pages serves them untouched). Re-run after new results.
"""

