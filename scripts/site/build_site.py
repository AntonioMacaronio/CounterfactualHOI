def copy_tree(src, dst):
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("*.zip"))


def add_nav(index_path, depth):
    """Put the site nav bar at the top of a copied tab page (the viewer HTMLs themselves stay untouched)."""
    s = open(index_path).read()
    bar = f"<style>{STYLE.split('main {')[0]}</style>{nav_html(depth)}"
    s = s.replace("<body>", "<body style=\"margin:0\">" + bar + "<div style=\"margin:24px\">", 1)
    s = s.replace("</body>", "</div></body>", 1)
    open(index_path, "w").write(s)


