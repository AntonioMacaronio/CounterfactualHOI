def nav_html(depth):
    up = "../" * depth
    links = "".join(f'<a href="{up}{href}">{html.escape(name)}</a>' for href, name in NAV)
    return f'<div class="nav"><b>CounterfactualHOI</b>{links}</div>'


def copy_tree(src, dst):
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("*.zip"))


def add_nav(index_path, depth):
    """Put the site nav bar at the top of a copied tab page (the viewer HTMLs themselves stay untouched)."""
    s = open(index_path).read()
    bar = f"<style>{STYLE.split('main {')[0]}</style>{nav_html(depth)}"
    s = s.replace("<body>", "<body style=\"margin:0\">" + bar + "<div style=\"margin:24px\">", 1)
    s = s.replace("</body>", "</div></body>", 1)
    open(index_path, "w").write(s)


def viewer(path_in_site, site_root, title, cap):
    """An embedded viewer (lazy-loaded) with the saved/default start camera passed in the URL."""
    q = camera_query(os.path.join(site_root, path_in_site))
    return (f'<figure class="card feature"><iframe src="{html.escape(path_in_site + q)}" title="{html.escape(title)}" '
            f'loading="lazy"></iframe><figcaption>{cap}</figcaption></figure>')


def compare_rows():
    p = os.path.join(OUTPUTS, "fprecon_viser", "compare.json")
    return [r for r in json.load(open(p)) if r.get("choir") and r.get("fprecon")] if os.path.exists(p) else []


def results_table(rows):
    if not rows:
        return "<p>(comparison not computed yet: scripts/fprecon/compare_choir.py)</p>"
    body = "".join(
        f"<tr><td>{r['clip']}</td><td>{r['choir']['iou_first_last'][0]:.2f} / {r['choir']['iou_first_last'][1]:.2f}</td>"
        f"<td><b>{r['fprecon']['iou_first_last'][0]:.2f} / {r['fprecon']['iou_first_last'][1]:.2f}</b></td>"
        f"<td>{100 * r['choir']['end_height_m']:+.1f} cm</td><td><b>{100 * r['fprecon']['end_height_m']:+.1f} cm</b></td>"
        f"<td>{r['fprecon']['depth_scale_from_hand']:.3f}</td></tr>" for r in rows)
    return ("<table><tr><th>clip</th><th>CHOIR mask IoU first / last</th><th>ours mask IoU first / last</th>"
            "<th>CHOIR object vs table at end</th><th>ours object vs table at end</th><th>depth scale from the hand</th></tr>"
            + body + "</table>")


def video_gallery(out):
    man = os.path.join(OUTPUTS, "minimax_h3", "manifest.jsonl")
    if not os.path.exists(man):
        return ""
    vdir = os.path.join(out, "videos")
    os.makedirs(vdir, exist_ok=True)
    figs = []
    for line in open(man):
        r = json.loads(line)
        if r.get("status") != "ok" or not r.get("compare") or not os.path.exists(r["compare"]):
            continue
        name = f"{r['clip']}_{r['mode']}_{r['variant']}.mp4"
        shutil.copyfile(r["compare"], os.path.join(vdir, name))
        label = f"{r['clip']} · {r['mode']} · {r['variant']}" + (f" ({r['category']})" if r.get("category") else "")
        figs.append(f'<figure class="card"><video src="videos/{name}" controls muted loop playsinline preload="metadata"></video>'
                    f"<figcaption>{html.escape(label)} — left: real source, right: MiniMax H3 generation</figcaption></figure>")
    return '<div class="gallery">' + "\n".join(figs) + "</div>"


def daid_table():
    rows = []
    for name, run, _obj, _fps, title, _port in DAID_CLIPS:
        try:
            rows.append(f"<tr><td>{html.escape(title)}</td><td>{daid_caption(os.path.join(DAID_RUNS, run))}</td></tr>")
        except (OSError, KeyError):
            rows.append(f"<tr><td>{html.escape(title)}</td><td>(QC not available)</td></tr>")
    return "<table><tr><th>clip</th><th>QC</th></tr>" + "".join(rows) + "</table>"


