def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(WORKDIR, "CounterfactualHOI-site"))
    ap.add_argument("--featured", default="prp_anthony_real_4", help="real clip shown for CHOIR and ours")
    ap.add_argument("--refine", default=f"refine_viser_r{ROUND}", help="outputs/ dir of the agent-refined viewers")
    ap.add_argument("--retarget", default="flashdex_viser", help="outputs/ dir of the retargeted motions")
    args = ap.parse_args()
    out, feat = args.out, args.featured
    os.makedirs(out, exist_ok=True)

    tabs = (("daid", "recon_viser"), ("choir", "choir_viser"), ("ours", "fprecon_viser"), ("agent", args.refine),
            ("retarget", args.retarget))
    retarget_round = []                                # the refinement round tab 5 was trained on, if not tab 4's
    have = {sub for sub, src in tabs if os.path.exists(os.path.join(OUTPUTS, src, "index.html"))}
    NAV[:] = [(h, n) for h, n in NAV if h == "index.html" or h.split("/")[1] in have]   # no links to missing tabs
    for sub, src in tabs:
        if sub not in have:
            continue
        copy_tree(os.path.join(OUTPUTS, src), os.path.join(out, "recon", sub))
        if sub in ("agent", "retarget"):               # their side-by-side tabs point at the other method's viewers
            ix = os.path.join(out, "recon", sub, "index.html")
            page = open(ix).read()
            # retargeting trained on an earlier refinement round than tab 4 shows: keep that round's viewers with it
            for other in sorted(set(re.findall(r"\.\./(refine_viser_\w+)/", page)) - {args.refine}):
                os.makedirs(os.path.join(out, "recon", sub, "ref"), exist_ok=True)
                for f in sorted(set(re.findall(rf"\.\./{other}/([\w.]+\.html)", page))):
                    shutil.copyfile(os.path.join(OUTPUTS, other, f), os.path.join(out, "recon", sub, "ref", f))
                page = page.replace(f"../{other}/", "ref/")
                retarget_round.append(other.split("_")[-1])
            page = page.replace("../fprecon_viser/", "../ours/").replace(f"../{args.refine}/", "../agent/")
            open(ix, "w").write(page)
        add_nav(os.path.join(out, "recon", sub, "index.html"), 2)
    stale = os.path.join(out, "recon", "index.html")           # the pre-restructure layout had "ours" at recon/
    if os.path.exists(stale):
        for f in os.listdir(os.path.join(out, "recon")):
            p = os.path.join(out, "recon", f)
            if os.path.isfile(p) or f == "qc":
                shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    os.makedirs(os.path.join(out, "img"), exist_ok=True)
    os.makedirs(os.path.join(out, "videos"), exist_ok=True)
    grid = os.path.join(WORKDIR, "videos", "grid2x2.mp4")
    if os.path.exists(grid):
        shutil.copyfile(grid, os.path.join(out, "videos", "daid_inputs_grid2x2.mp4"))
    retarget_img = os.path.join(STORAGE, "tmp", "retarget_IMG5710_tiles.jpg")
    has_retarget_img = os.path.exists(retarget_img)
    if has_retarget_img:
        shutil.copyfile(retarget_img, os.path.join(out, "img", "retarget_IMG5710.jpg"))
    gallery = video_gallery(out)
    rows = compare_rows()
    feat_row = next((r for r in rows if r["clip"] == feat), None)

    choir_cap = (f"<b>Open-CHOIR · {feat}</b> (gray mug, picked up, rotated in the hand, set down)"
                 + (f" — mask IoU first / last {feat_row['choir']['iou_first_last'][0]:.2f} / "
                    f"{feat_row['choir']['iou_first_last'][1]:.2f}; object ends "
                    f"{100 * feat_row['choir']['end_height_m']:+.1f} cm from the table" if feat_row else ""))
    ours_cap = (f"<b>Our pipeline · {feat}</b> (same clip)"
                + (f" — mask IoU first / last {feat_row['fprecon']['iou_first_last'][0]:.2f} / "
                   f"{feat_row['fprecon']['iou_first_last'][1]:.2f}; object ends "
                   f"{100 * feat_row['fprecon']['end_height_m']:+.1f} cm from the table" if feat_row else ""))
    howto = "Drag to orbit, scroll to zoom; playback bar at the bottom."
    rtable, rmed = refine_table(os.path.join(out, "recon", "agent"))
    abl = ablation_rows()
    abl_table = ("<table><tr><th>A</th><th>B</th><th>A better</th><th>B better</th><th>tie</th><th>clips</th></tr>" + "".join(
        f"<tr><td>{a}</td><td>{b}</td><td>{wa}</td><td>{wb}</td><td>{t}</td><td>{n}</td></tr>" for a, b, wa, wb, t, n in abl)
        + "</table>") if abl else ""
    feat_sum = os.path.join(out, "recon", "agent", "summary", f"{feat}.json")
